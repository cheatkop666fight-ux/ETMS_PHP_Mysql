<?php

session_start();


/*
|--------------------------------------------------------------------------
| Check login
|--------------------------------------------------------------------------
*/

if (
    !isset($_SESSION["user_id"]) ||
    !isset($_SESSION["role"])
) {

    header("Location: ../auth/login.php");
    exit;

}


/*
|--------------------------------------------------------------------------
| Check employee role
|--------------------------------------------------------------------------
*/

if ($_SESSION["role"] !== "employee") {

    http_response_code(403);

    die("Access denied.");

}


/*
|--------------------------------------------------------------------------
| Send employee to dashboard
|--------------------------------------------------------------------------
*/

header("Location: dashboard.php");
exit;

?>

